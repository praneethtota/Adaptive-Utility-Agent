from aua.confidence_updater import ConfidenceUpdater

log = logging.getLogger("aua.router")


# ── Request / Response models ─────────────────────────────────────────────────

class QueryRequest(BaseModel):
    query: str = Field(..., description="The query to route through the specialist graph.")
    session_id: Optional[str] = Field("default", description="Session identifier for cross-session assertions.")
    conversation_history: Optional[List[dict]] = Field([], description="Prior turns as [{role, content}].")
    force_domain: Optional[str] = Field(None, description="Override domain routing (for testing).")


class RouterResponse(BaseModel):
    query: str
    routing_mode: str = Field(..., description="single | fanout | arbiter")
    domain_distribution: Dict[str, float]
    primary_domain: str
    response: str
    u_score: float
    confidence: float
    contradictions_detected: int
    dpo_pairs_generated: int
    latency_ms: float
    specialist_responses: Optional[List[dict]] = None


class BatchQueryRequest(BaseModel):
    queries: List[str] = Field(..., description="List of queries to process in parallel.")
    session_id: Optional[str] = "default"
    max_parallel: Optional[int] = Field(4, description="Max concurrent specialist calls.")


class BatchQueryResponse(BaseModel):
    results: List[RouterResponse]
    total_latency_ms: float
    n_queries: int
    n_errors: int


class CorrectionRequest(BaseModel):
    subject: str = Field(..., description="Short subject label (e.g. 'bubble_sort_complexity').")
    domain: str = Field(..., description="Field name (e.g. 'software_engineering').")
    claim: str = Field(..., description="The correction claim to store.")
    confidence: float = Field(0.9, ge=0.0, le=1.0, description="Confidence in this correction.")
    source: Optional[str] = Field("manual", description="Source label for the correction.")


class CorrectionResponse(BaseModel):
    stored: bool
    subject: str
    domain: str
    claim: str
    confidence: float
    decay_class: str


class DeployGreenRequest(BaseModel):
    specialist: str = Field(..., description="Specialist name to evaluate (e.g. 'swe').")
    green_model: str = Field(..., description="Path or HF ID of the GREEN model to evaluate.")
    n_eval_queries: Optional[int] = Field(10, description="Number of queries to run in evaluation.")


class DeployGreenResponse(BaseModel):
    specialist: str
    promoted: bool
    u_delta: float
    blue_u: float
    green_u: float
    threshold: float
    message: str


# ── Router ────────────────────────────────────────────────────────────────────

class Router:
    """
    Micro-Expert Architecture Router.

    Routes each query to the right specialist based on field classification,
    fans out to multiple specialists on cross-domain queries, runs the Arbiter
    on conflicts, and accumulates DPO pairs from detected contradictions.

    All routing parameters come from AUAConfig — no hardcoded ports or
    thresholds anywhere in this class.
    """

    def __init__(self, config: AUAConfig) -> None:
        self._config     = config
        self._classifier = FieldClassifier()
        self._scorer     = UtilityScorer()
        self._store      = AssertionsStore()
        self._detector   = ContradictionDetector(penalty_multiplier=2.0)
        self._conf       = ConfidenceUpdater()

        self._domain_confidence: Dict[str, float] = {
            s.field: 0.5 for s in config.specialists
        }
        self._field_to_url: Dict[str, str] = {
            s.field: s.endpoint for s in config.specialists
        }
        self._arbiter_url = config.arbiter.endpoint
        self._single_threshold = config.router.single_domain_threshold
        self._fanout_threshold = config.router.fanout_threshold
        self._timeout = config.router.specialist_timeout

        # ── Telemetry ─────────────────────────────────────────────────────
        self._start_time: float = time.time()
        self._queries_by_mode: Dict[str, int] = {"single": 0, "fanout": 0, "arbiter": 0}
        self._latencies_ms: Dict[str, deque] = defaultdict(lambda: deque(maxlen=200))
        self._requests_per_spec: Dict[str, int] = {s.name: 0 for s in config.specialists}
        self._requests_per_spec["arbiter"] = 0
        self._total_contradictions: int = 0
        self._total_dpo: int = 0
        self._verdict_counts: Dict[str, int] = {
            "case_1": 0, "case_2": 0, "case_3": 0, "case_4": 0
        }
        # Startup flag — set True once first health check passes
        self._started: bool = False

        self.app = self._build_app()
        log.info(
            "Router initialised — %d specialist(s), arbiter on port %d",
            len(config.specialists), config.arbiter.port,
        )

    # ── Factory ───────────────────────────────────────────────────────────────

    @classmethod
    def from_config(cls, config: AUAConfig) -> "Router":
        return cls(config)

    # ── Public query API ──────────────────────────────────────────────────────

    async def query(
        self,
        query: str,
        session_id: str = "default",
        conversation_history: Optional[List[dict]] = None,
        force_domain: Optional[str] = None,
    ) -> RouterResponse:
        """Route a query programmatically (library API, not HTTP)."""
        req = QueryRequest(
            query=query,
            session_id=session_id,
            conversation_history=conversation_history or [],
            force_domain=force_domain,
        )
        return await self._handle(req)

    # ── FastAPI app ───────────────────────────────────────────────────────────

    def _build_app(self) -> FastAPI:
        app = FastAPI(
            title="AUA Micro-Expert Router",
            description=(
                "Adaptive Utility Agents — routes queries to specialist LLM models, "
                "arbitrates cross-domain conflicts, and accumulates DPO corrections.\n\n"
                "Config-driven via `aua_config.yaml`. "
                "Start with `aua serve`, inspect with `aua status`."
            ),
            version="0.5.0",
            docs_url="/docs",
            redoc_url="/redoc",
            openapi_tags=[
                {"name": "query",       "description": "Route queries through the specialist graph."},
                {"name": "health",      "description": "Kubernetes-compatible liveness / readiness / startup probes."},
                {"name": "corrections", "description": "Manually inject or inspect the corrections store."},
                {"name": "config",      "description": "Inspect the running configuration."},
                {"name": "deploy",      "description": "Blue-green promotion."},
                {"name": "telemetry",   "description": "Live telemetry and dashboard data."},
            ],
        )
        app.add_middleware(
            CORSMiddleware,
            allow_origins=["*"],
            allow_methods=["*"],
            allow_headers=["*"],
        )

        # ── Query endpoints ────────────────────────────────────────────────

        @app.post(
            "/query",
            response_model=RouterResponse,
            tags=["query"],
            summary="Route a query through the specialist graph",
        )
        async def route(req: QueryRequest):
            """
            Route a single query through the Micro-Expert Architecture.

            - Classifies the query domain
            - Routes to the correct specialist (or fans out across multiple)
            - Runs the Arbiter on cross-domain conflicts
            - Scores with the utility function U = w_e·E + w_c·C + w_k·K
            - Accumulates DPO pairs from detected contradictions
            """
            return await self._handle(req)

        @app.post(
            "/query/batch",
            response_model=BatchQueryResponse,
            tags=["query"],
            summary="Batch inference — route multiple queries in parallel",
        )
        async def batch_route(req: BatchQueryRequest):
            """
            Route a list of queries concurrently, up to `max_parallel` at once.
            Returns one RouterResponse per query, plus aggregate stats.
            """
            return await self._handle_batch(req)

        # ── Health probes (Kubernetes-compatible) ──────────────────────────

        @app.get(
            "/health/live",
            tags=["health"],
            summary="Liveness probe — is the process alive?",
        )
        async def health_live():
            """
            Always returns 200 if the router process is running.
            Kubernetes uses this to decide whether to restart the container.
            """
            return {"status": "alive", "uptime_s": round(time.time() - self._start_time, 1)}

        @app.get(
            "/health/ready",
            tags=["health"],
            summary="Readiness probe — are all specialists reachable?",
        )
        async def health_ready():
            """
            Pings all specialist and arbiter endpoints.
            Returns 200 only if all are reachable.
            Kubernetes uses this to gate traffic.
            """
            health = await self._health()
            specialists = health["specialists"]
            all_up = all(v == "ok" for v in specialists.values())
            if not all_up:
                down = [k for k, v in specialists.items() if v != "ok"]
                raise HTTPException(
                    status_code=503,
                    detail={"status": "not_ready", "down": down, "specialists": specialists}
                )
            self._started = True
            return {"status": "ready", "specialists": specialists}

        @app.get(
            "/health/startup",
            tags=["health"],
            summary="Startup probe — has the framework completed initialisation?",
        )
        async def health_startup():
            """
            Returns 200 once the router has successfully completed at least one
            readiness check. Kubernetes uses this to delay liveness checks during
            slow model loading.
            """
            if not self._started:
                # Try a health check now
                health = await self._health()
                all_up = all(v == "ok" for v in health["specialists"].values())
                if all_up:
                    self._started = True
            if not self._started:
                raise HTTPException(
                    status_code=503,
                    detail={"status": "starting", "message": "Specialists not yet healthy"}
                )
            return {"status": "started", "uptime_s": round(time.time() - self._start_time, 1)}

        # Legacy /health kept for backwards compatibility
        @app.get("/health", tags=["health"], include_in_schema=False)
        async def health_legacy():
            return await self._health()

        # ── Corrections ────────────────────────────────────────────────────

        @app.post(
            "/corrections",
            response_model=CorrectionResponse,
            tags=["corrections"],
            summary="Inject a correction manually into the assertions store",
        )
        async def inject_correction(req: CorrectionRequest):
            """
            Manually inject a verified fact into the cross-session assertions store.
            Injected corrections are used to prime specialist prompts on future queries
            to the same domain/subject, reducing repeated errors.

            Example use case: after a specialist gives a wrong answer that you verify
            externally, inject the correct claim so it never gives that answer again.
            """
            assertion = self._store.add(
                subject=req.subject,
                domain=req.domain,
                claim=req.claim,
                confidence=req.confidence,
                source=req.source or "manual",
            )
            return CorrectionResponse(
                stored=True,
                subject=assertion.subject,
                domain=assertion.domain,
                claim=assertion.claim,
                confidence=round(assertion.effective_confidence(), 4),
                decay_class=assertion.decay_class.value,
            )

        @app.get(
            "/corrections",
            tags=["corrections"],
            summary="List stored corrections",
        )
        async def list_corrections(
            subject: Optional[str] = None,
            domain: Optional[str] = None,
            limit: int = 50,
        ):
            """List corrections in the assertions store, optionally filtered by subject/domain."""
            matches = self._store.query(
                subject=subject or "",
                domain=domain,
            )[:limit]
            return {
                "total": self._store.summary()["total"],
                "returned": len(matches),
                "corrections": [
                    {
                        "subject": m.assertion.subject,
                        "domain": m.assertion.domain,
                        "claim": m.assertion.claim,
                        "effective_confidence": m.effective_confidence,
                        "decay_class": m.assertion.decay_class.value,
                        "source": m.assertion.source,
                    }
                    for m in matches
                ],
            }

