"""
aua/router.py — Micro-Expert Architecture Router

Config-driven: all specialist endpoints, thresholds, and ports come from
AUAConfig (loaded from aua_config.yaml). No hardcoded values.

REST API (#09):
    POST /query              route a query through the specialist graph
    POST /query/batch        batch inference (list of queries)
    GET  /health/live        liveness probe  (Kubernetes-compatible)
    GET  /health/ready       readiness probe (all specialists reachable)
    GET  /health/startup     startup probe   (framework initialised)
    POST /corrections        inject a correction manually
    GET  /config             current loaded config (read-only)
    POST /deploy/green       trigger blue-green promotion check
    GET  /status             full telemetry dashboard (aua status)
    GET  /docs               Swagger UI  (auto-generated by FastAPI)
    GET  /redoc              ReDoc       (auto-generated by FastAPI)
"""

